"""Map every Starstone model face onto a 16x16 texture window of its own size (1 texel = 1 unit).

    python -B mods/starstone/tools/make_block_models.py

Rewrites the UVs of the hand-made block models in place; build_inner_corner.py calls assign_uvs()
for the generated Inner Corner model. The windows are LAYOUT in make_block_art.py. A face whose long
side runs along its V axis gets uv_rotation 90, so a strip always runs along the part.
Thin faces (one unit or less) sample a one-texel row of the matching window.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_block_art import LAYOUT  # noqa: E402
from starstone_art import RP  # noqa: E402

MODELS = RP / 'models' / 'blocks'
TEXTURE_SIZE = 16
# Which texture region each bone samples, per geometry; anything unlisted is a conductor arm.
ROLES = {
    'geometry.starstone_cable': {'center': 'hub'},
    'geometry.starstone_inner_corner': {'center_': 'hub'},
    'geometry.starstone_adapter': {'center': 'plate'},
    'geometry.starstone_bridge': {'body': 'plate'},
    'geometry.starstone_surface_device': {'panel': 'panel', 'contacts': 'contact'},
    'geometry.starstone_conduit': {'conduit': 'full'},
}
# Face -> indices of the cube size that run along its U and V.
FACE_AXES = {'up': (0, 2), 'down': (0, 2), 'north': (0, 1), 'south': (0, 1), 'east': (2, 1), 'west': (2, 1)}


def window(role, long, short):
    """Texture window for a face of the given rounded long and short side (short 0 = thin face)."""
    if role == 'full':
        return (0, 0, 16, 16)
    if role == 'contact':
        return LAYOUT['contact_side_long' if long == 4 else 'contact_side_short'] if short == 0 else None
    if short == 0:
        thin = {'hub': 'hub_side', 'plate': 'plate_side', 'panel': 'panel_side'}.get(role)
        return LAYOUT[thin or {6: 'arm_side6', 5: 'arm_side5', 2: 'arm_end'}[long]]
    return LAYOUT[{'hub': 'hub', 'plate': 'plate', 'panel': 'panel'}.get(role) or {6: 'arm6', 5: 'arm5'}[long]]


def role_of(geometry_id, bone):
    for prefix, role in ROLES.get(geometry_id, {}).items():
        if bone == prefix or (prefix.endswith('_') and bone.startswith(prefix)):
            return role
    return 'arm'


def face_uv(role, face, size, old):
    du, dv = (size[i] for i in FACE_AXES[face])
    long, short = max(du, dv), min(du, dv)
    long, short = round(long), (round(short) if short > 1 else 0)
    entry = {k: v for k, v in old.items() if k == 'material_instance'}
    if role == 'contact' and short:
        # Contacts are painted in both orientations on the lamp tile.
        x, y, w, h = LAYOUT['contact_ns' if du > dv else 'contact_ew']
        rotate = False
    else:
        x, y, w, h = window(role, long, short)
        rotate = du < dv and role != 'full'
    assert (w, h) == ((long, max(short, 1)) if role != 'full' else (16, 16)) or role == 'contact', \
        f'{role} {face} {size}: window {w}x{h} does not match the face'
    entry.update({'uv': [x, y], 'uv_size': [w, h]})
    if rotate:
        entry['uv_rotation'] = 90
    return entry


def assign_uvs(geometry):
    """Rewrite every cube's per-face UVs of one geometry entry (dict with description and bones)."""
    desc = geometry['description']
    desc['texture_width'] = desc['texture_height'] = TEXTURE_SIZE
    for bone in geometry['bones']:
        role = role_of(desc['identifier'], bone['name'])
        for cube in bone.get('cubes', []):
            old = cube['uv'] if isinstance(cube['uv'], dict) else {f: {} for f in FACE_AXES}
            cube['uv'] = {face: face_uv(role, face, cube['size'], spec) for face, spec in old.items()}
    return geometry


def main():
    for path in sorted(MODELS.glob('*.geo.json')):
        if 'inner_corner' in path.name:
            continue  # generated by build_inner_corner.py, which calls assign_uvs itself
        data = json.loads(path.read_text(encoding='utf-8'))
        for geometry in data['minecraft:geometry']:
            assign_uvs(geometry)
        path.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8', newline='\n')
        print('updated', path.name)


if __name__ == '__main__':
    main()
